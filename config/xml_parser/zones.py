"""Safety zones: the cell files (config/cells/<name>.xml), the gripper's tool spheres, and the haptic-wall
policy from system.xml with its stability table (HAPTIC_STABLE). Unlike the policy blocks, a bad zone is
an ERROR, never a fallback.

Split out of the single-file config/xml_parser.py on 2026-10-03 (refactor Phase 4); definitions moved verbatim.
"""

from __future__ import annotations

import logging
import xml.etree.ElementTree as ET
from pathlib import Path


# --------------------------------------------------------------------------------------- safety zones
# Zones describe the CELL (TODO/safety_zones_plan.md, docs/safety_zones.md): config/cells/<name>.xml,
# chosen by <active_cell> in system.xml; empty = no zones. Unlike the policy blocks above, a bad zone
# is an ERROR, never a fallback — falling back would mean "no zone", i.e. silently disarming it.

_ZONE_TAGS = {
    "box":      {"min": 3, "max": 3},
    "prism":    {"z_min": 1, "z_max": 1},            # plus 3-16 <vertex>x y</vertex>
    "cylinder": {"p1": 3, "p2": 3, "radius": 1},
    "sphere":   {"center": 3, "radius": 1},
    "plane":    {"point": 3, "normal": 3},
}


_ZONE_ATTRS = {"name", "shape", "kind", "reaction", "checks", "margin", "enabled", "rounded", "haptic", "freedrive"}


# Haptic walls (utility/haptic_walls.py): in IDLE gravity-comp freedrive, zones with haptic="1" push back like a
# spring-damper, and every joint gets the same wall at its soft limit (J6, no endstop: its hard limit). Robot-
# independent policy, so system.xml; read by load_zone_setup so reload_zones can retune it without a restart. The
# per-joint settings (position, stiffness, reaction, ...) are the arm's: <freedrive_wall> in the robot XML.
_HAPTIC_FALLBACK = {
    "enabled":          1,
    "stiffness":        200.0,     # N/m — stable for an effective TCP mass down to 0.1 kg (see HAPTIC_STABLE)
    "damping":          6.0,       # N.s/m, both ways inside the wall (the force is clamped so it never pulls)
    "max_force":        15.0,      # N per robot sphere in contact
    "breakthrough":     0.03,      # m past the zone's surface = pushed through (the zone's freedrive reaction)
    "velocity_tau":     0.004,     # s, the wall's own EMA of the RAW speed (the 10 ms filtered one is unstable)
    "zone_mass_scaled": 1,         # zone walls x the contact's effective mass / 0.1 kg (haptic_walls MASS-NORMALISED)
    "joint_walls":      1,         # every joint: a wall at its soft limit (no endstop: at the hard limit)
    "joint_max_torque": 20.0,      # Nm: the CEILING for any joint wall setting (auto stays <= 5 Nm; per-joint values: robot XML)
    "joint_breakthrough": 15.0,    # deg: auto breakthrough, at most (a soft-limit wall: the margin to the hard limit)
}


_HAPTIC_BOUNDS = {
    "enabled":          (0, 1),
    "stiffness":        (0.0, 750.0),
    "damping":          (0.0, 25.0),
    "max_force":        (0.0, 60.0),
    "breakthrough":     (0.005, 0.2),
    "velocity_tau":     (0.0, 0.008),
    "zone_mass_scaled": (0, 1),
    "joint_walls":      (0, 1),
    "joint_max_torque": (0.0, 30.0),
    "joint_breakthrough": (2.0, 90.0),
}


# Stiffness -> stable damping window (N.s/m), per velocity filter (ms). Simulated 2026-10-01 (utility/haptic_walls.py
# STABILITY; test_haptic_walls.py re-checks every cell): a mass of 0.1-5 kg bouncing on the wall must never gain
# energy, with the state 1 tick old as in RTI. 0.1 kg because the arm's effective TCP mass along J5's direction of
# travel is 0.13 kg in the model — the shipped 1000 N/m wall was unstable there and vibrated on the arm.
# Lookup is conservative: stiffness and filter are rounded UP to the next row/column (windows shrink with both).
# Generated by tools/haptic_stability_table.py; the 1-3 and 5-7 ms columns and the 400 / 600 N/m rows added
# 2026-10-02 (per-joint filter, finer maximum frequency; user requests) — the same method reproduces the original
# cells exactly. A window under 2 N.s/m wide is left out (no margin: 1000 N/m at 0 ms is passive at exactly
# 11 N.s/m and nothing else; 600 N/m at 5 ms at exactly 9).
HAPTIC_STABLE = {
    0: {100: (1, 23), 200: (2, 22), 300: (3, 21), 400: (3, 20), 500: (4, 19), 600: (5, 18), 750: (7, 17)},
    1: {100: (1, 23), 200: (2, 22), 300: (3, 21), 400: (3, 20), 500: (4, 19), 600: (5, 18), 750: (7, 17)},
    2: {100: (1, 21), 200: (2, 20), 300: (3, 19), 400: (3, 19), 500: (4, 18), 600: (5, 17), 750: (7, 16)},
    3: {100: (1, 20), 200: (2, 19), 300: (3, 18), 400: (4, 18), 500: (5, 17), 600: (6, 15), 750: (9, 12)},
    4: {100: (1, 19), 200: (2, 18), 300: (3, 18), 400: (4, 16), 500: (5, 14), 600: (7, 12)},
    5: {100: (1, 18), 200: (2, 17), 300: (3, 15), 400: (4, 14), 500: (5, 13)},
    6: {100: (1, 16), 200: (2, 15), 300: (3, 14), 400: (4, 13), 500: (6, 10)},
    7: {100: (1, 15), 200: (2, 14), 300: (3, 13), 400: (5, 11)},
    8: {100: (1, 15), 200: (2, 13), 300: (3, 12), 400: (5, 9)},
}


HAPTIC_REFERENCE_MASS = 0.1     # kg: the lightest effective mass the table covers


def haptic_damping_window(stiffness: float, tau_s: float) -> tuple[float, float] | None:
    """(d_min, d_max) for which a wall of `stiffness` (N/m) is passive with a `tau_s` velocity filter, or None."""
    if stiffness <= 0.0:
        return (0.0, float("inf"))
    taus = [t for t in sorted(HAPTIC_STABLE) if t >= tau_s * 1000.0 - 1e-9]
    if not taus:
        return None
    row = HAPTIC_STABLE[taus[0]]
    ks = [k for k in sorted(row) if k >= stiffness - 1e-9]
    return tuple(float(v) for v in row[ks[0]]) if ks else None


def _parse_haptic_walls(elem: ET.Element | None) -> dict:
    """<haptic_walls> in system.xml. Missing or out-of-range values fall back with a warning (a fallback here only
    changes how a wall FEELS; the monitor still watches). A stiffness/damping/filter combination outside the
    simulated-stable region (HAPTIC_STABLE) falls back to the defaults: an unstable wall buzzes and moves the arm."""
    out = dict(_HAPTIC_FALLBACK)
    if elem is None:
        return out
    for key, default in _HAPTIC_FALLBACK.items():
        text = elem.findtext(key, default="").strip()
        if not text:
            continue
        try:
            val = int(text) if isinstance(default, int) else float(text)
        except ValueError:
            logging.warning("[system.xml] <haptic_walls><%s> is not a number (%r) — using %s", key, text, default)
            continue
        lo, hi = _HAPTIC_BOUNDS[key]
        if not (lo <= val <= hi):
            logging.warning("[system.xml] <haptic_walls><%s> = %s is outside [%s, %s] — using %s", key, val, lo, hi, default)
            continue
        out[key] = val
    k, d, tau = out["stiffness"], out["damping"], out["velocity_tau"]
    win = haptic_damping_window(k, tau)
    if win is None or not (win[0] <= d <= win[1]):
        logging.warning("[system.xml] <haptic_walls> stiffness %s N/m, damping %s N.s/m, filter %.0f ms is outside the "
                        "region simulated stable (%s) — using %s / %s / %s ms", k, d, 1000 * tau,
                        "no stable damping at that stiffness/filter" if win is None else f"damping {win[0]:g}-{win[1]:g}",
                        _HAPTIC_FALLBACK["stiffness"], _HAPTIC_FALLBACK["damping"], 1000 * _HAPTIC_FALLBACK["velocity_tau"])
        out["stiffness"], out["damping"] = _HAPTIC_FALLBACK["stiffness"], _HAPTIC_FALLBACK["damping"]
        out["velocity_tau"] = _HAPTIC_FALLBACK["velocity_tau"]
    return out


def _zone_numbers(text: str | None, n: int, what: str) -> list[float]:
    parts = (text or "").split()
    try:
        vals = [float(x) for x in parts]
    except ValueError:
        raise ValueError(f"{what}: not numbers: {text!r}") from None
    if len(vals) != n:
        raise ValueError(f"{what}: expected {n} number(s), got {len(vals)} ({text!r})")
    return vals


def parse_cell_zones(path: str | Path) -> list[dict]:
    """Read one cell file -> list of validated zones (utility.zones.make_zone). Raises ValueError."""
    from utility.zones import check_unique_names, make_zone
    path = Path(path)
    try:
        root = ET.parse(str(path)).getroot()
    except ET.ParseError as e:
        raise ValueError(f"{path.name}: not valid XML ({e})") from None
    if root.tag != "cell":
        raise ValueError(f"{path.name}: the root element must be <cell>, got <{root.tag}>")
    stray = sorted({c.tag for c in root} - {"zone"})
    if stray:
        raise ValueError(f"{path.name}: unknown element(s) {stray} — a cell holds only <zone> elements")
    zones = []
    for i, el in enumerate(root.findall("zone")):
        where = f"{path.name} zone {i + 1} ('{el.get('name', '')}')"
        shape = el.get("shape", "")
        if shape not in _ZONE_TAGS:
            raise ValueError(f"{where}: shape must be one of {sorted(_ZONE_TAGS)}, got {shape!r}")
        if el.get("kind") is None:
            raise ValueError(f'{where}: kind="allowed" or kind="forbidden" is required')
        extra_attrs = sorted(set(el.keys()) - _ZONE_ATTRS)
        if extra_attrs:
            raise ValueError(f"{where}: unknown attribute(s) {extra_attrs}")
        tags = _ZONE_TAGS[shape]
        extra = sorted({c.tag for c in el} - set(tags) - ({"vertex"} if shape == "prism" else set()))
        if extra:
            raise ValueError(f"{where}: unknown element(s) {extra} for a {shape}")
        geo = {}
        for tag, n in tags.items():
            text = el.findtext(tag)
            if text is None:
                raise ValueError(f"{where}: missing <{tag}>")
            vals = _zone_numbers(text, n, f"{where} <{tag}>")
            geo[tag] = vals[0] if n == 1 else vals
        if shape == "prism":
            geo["vertices"] = [_zone_numbers(v.text, 2, f"{where} <vertex>") for v in el.findall("vertex")]
        if shape == "cylinder" and el.get("rounded") is not None:
            geo["rounded"] = el.get("rounded").strip()
        enabled = el.get("enabled", "1").strip()
        if enabled not in ("0", "1"):
            raise ValueError(f"{where}: enabled must be 0 or 1, got {enabled!r}")
        try:
            zones.append(make_zone(el.get("name", ""), shape, el.get("kind"),
                                   reaction=el.get("reaction", "stop"), checks=el.get("checks", "tool"),
                                   margin=el.get("margin", "0"), enabled=enabled == "1",
                                   haptic=el.get("haptic", "1").strip(), freedrive=el.get("freedrive", "warn").strip(),
                                   **geo))
        except ValueError as e:
            raise ValueError(f"{path.name}: {e}") from None
    check_unique_names(zones, path.name)
    return zones


def parse_tool_spheres(gripper_xml_path: str | Path) -> list[tuple[float, ...]]:
    """<tool_spheres><sphere>x y z r</sphere>...</tool_spheres> from a gripper XML: spheres in the TCP
    frame, metres. No file or no block = no tool spheres (only the TCP point is checked)."""
    from utility.zones import robot_spheres
    path = Path(gripper_xml_path)
    if not path.exists():
        return []
    block = ET.parse(str(path)).getroot().find("tool_spheres")
    if block is None:
        return []
    spheres = [_zone_numbers(s.text, 4, f"{path.name} <tool_spheres><sphere> {i + 1}")
               for i, s in enumerate(block.findall("sphere"))]
    try:
        return [tuple(s) for s in robot_spheres(spheres)[1:]]
    except ValueError as e:
        raise ValueError(f"{path.name}: {e}") from None


def load_zone_setup(system_xml_path: str | Path, cells_dir: str | Path, gripper_xml_path: str | Path | None = None) -> dict:
    """The zones in force: <active_cell> from system.xml plus the gripper's tool spheres.

    Returns {"cell": name or "", "zones": [...], "tool_spheres": [(x, y, z, r), ...], "haptic": {...}}
    (the <haptic_walls> policy). Raises on a bad
    or missing cell file — callers must refuse to run rather than run without the zones.
    """
    import re
    root = ET.parse(str(system_xml_path)).getroot()
    cell = (root.findtext("active_cell") or "").strip()
    zones = []
    if cell:
        if not re.match(r"^[A-Za-z0-9_-]+$", cell):
            raise ValueError(f"[system.xml] active_cell={cell!r}: use letters, digits, '_' or '-' (a file name "
                             f"in config/cells/ without .xml)")
        path = Path(cells_dir) / f"{cell}.xml"
        if not path.exists():
            available = sorted(p.stem for p in Path(cells_dir).glob("*.xml"))
            raise FileNotFoundError(f"[system.xml] active_cell='{cell}' but {path} does not exist. "
                                    f"Available cells: {available}")
        zones = parse_cell_zones(path)
    spheres = parse_tool_spheres(gripper_xml_path) if gripper_xml_path else []
    return {"cell": cell, "zones": zones, "tool_spheres": spheres,
            "haptic": _parse_haptic_walls(root.find("haptic_walls"))}


def zone_setup_from_wire(wire: dict) -> dict:
    """The zone setup REBUILT from its JSON form (utility.zones.zones_summary: {"cell", "zones": [public_zone...],
    "tool_spheres", "haptic_walls"}) — what command_executor sends with reload_zones since 2026-10-04, so the RT
    process parses no file in its loop. Every zone goes through make_zone again (the same validation as the cell
    parser); raises ValueError / KeyError / TypeError on anything malformed, and the caller keeps its zones."""
    from utility.zones import check_unique_names, make_zone
    if not isinstance(wire, dict):
        raise TypeError("zone setup must be a dict")
    zones = []
    for z in wire.get("zones") or ():
        geometry = dict(z.get("geometry") or {})
        zones.append(make_zone(str(z["name"]), str(z["shape"]), str(z["kind"]), reaction=z.get("reaction", "stop"),
                               checks=z.get("checks", "tool"), margin=z.get("margin", 0.0), enabled=bool(z.get("enabled", True)),
                               haptic=z.get("haptic", True), freedrive=z.get("freedrive", "warn"), **geometry))
    check_unique_names(zones, "reload_zones")
    spheres = [tuple(float(v) for v in sph) for sph in (wire.get("tool_spheres") or ())]
    return {"cell": str(wire.get("cell") or ""), "zones": zones, "tool_spheres": spheres,
            "haptic": dict(wire.get("haptic_walls") or {})}

